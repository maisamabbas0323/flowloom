import * as fs from 'node:fs'
import * as path from 'node:path'
import type {
  GraphValidationIssue,
  WorkflowGraph,
  WorkflowRecord,
  WorkflowSaveResult,
  WorkflowSummary
} from '../../shared/contracts'
import type { WorkflowNode, WorkflowEdge } from '../../shared/nodeSchema'
import { validateWorkflowGraph, WORKFLOW_SCHEMA_VERSION } from '../../shared/nodeSchema'
import { JsonStore } from '../lib/jsonStore'
import type { Logger } from '../lib/log'

/**
 * Workflow record persistence — the main process is the authority for
 * what may be saved. Plain JSON files in the app configuration
 * directory: no database is needed at this size, and the format stays
 * readable and portable.
 *
 * Structural problems block saving; per-node configuration problems do
 * not (an unfinished workflow is still a real record the user can come
 * back to), but they are reported to the editor so nothing claims the
 * workflow is runnable.
 */
export class WorkflowService {
  private index: JsonStore<WorkflowIndex>

  constructor(
    directory: string,
    private readonly logger: Logger
  ) {
    this.dataDir = directory
    this.index = new JsonStore<WorkflowIndex>(
      path.join(directory, 'index.json'),
      defaultIndex,
      logger
    )
  }

  private dataDir: string

  private filePathFor(id: string): string {
    // ids are generated by this service only (`wf_` + base36 chars) — a
    // basic sanity check guards against anything path-like sneaking in.
    if (!/^[a-zA-Z0-9_-]{6,64}$/.test(id)) throw new Error('Invalid workflow id.')
    return path.join(this.dataDir, `${id}.json`)
  }

  list(): WorkflowSummary[] {
    const files = this.index.read().workflows
    return [...files]
      .filter((wf) => fs.existsSync(this.filePathFor(wf.id)))
      .sort((a, b) => {
        if (a.updatedAt < b.updatedAt) return 1
        if (a.updatedAt > b.updatedAt) return -1
        return 0
      })
  }

  create(input: { name: string }): WorkflowRecord {
    const trimmed = input.name.trim().slice(0, 120) || 'Untitled workflow'
    const now = new Date().toISOString()
    const record: WorkflowRecord = {
      id: generateId(),
      name: trimmed,
      description: '',
      createdAt: now,
      updatedAt: now,
      lastOpenedAt: now,
      graph: { schemaVersion: WORKFLOW_SCHEMA_VERSION, nodes: [], edges: [] },
      view: null
    }
    this.persistRecord(record)
    this.upsertIndex(record)
    return record
  }

  get(id: string): WorkflowRecord | null {
    try {
      const raw = fs.readFileSync(this.filePathFor(id), 'utf8')
      const record = JSON.parse(raw) as WorkflowRecord
      if (!isRecordShape(record)) return null
      // Opening a workflow marks it as recently used (last-opened tracking).
      const now = new Date().toISOString()
      record.lastOpenedAt = now
      this.persistRecord(record)
      this.upsertIndex(record)
      return record
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'ENOENT') {
        this.logger.error(`Failed to read workflow '${id}'.`, error)
      }
      return null
    }
  }

  /**
   * Persists a workflow. The graph is validated here regardless of what
   * the renderer checked — the main process is the authority.
   */
  save(input: {
    id: string
    name: string
    description?: string
    graph: WorkflowGraph
    view?: { zoom: number; x: number; y: number } | null
  }): WorkflowSaveResult {
    // Validate the id up front so a malformed id fails loudly here
    // instead of surfacing as a silent not-found below.
    this.filePathFor(input.id)
    const current = this.readWithoutTouch(input.id)
    if (!current) {
      return {
        ok: false,
        errors: ['This workflow was deleted or never existed — reopen it from the Workflows page.']
      }
    }

    const graph = sanitizeGraph(input.graph)
    const validation = validateWorkflowGraph(graph)
    if (!validation.structural) {
      return { ok: false, errors: validation.structuralErrors }
    }

    const now = new Date().toISOString()
    const updated: WorkflowRecord = {
      ...current,
      name: input.name.trim().slice(0, 120) || current.name,
      description: typeof input.description === 'string' ? input.description.slice(0, 400) : current.description,
      updatedAt: now,
      graph,
      view: input.view === undefined ? current.view : sanitizeView(input.view)
    }
    this.persistRecord(updated)
    this.upsertIndex(updated)
    return {
      ok: true,
      record: updated,
      configIssues: incompleteNodeMessages(updated.graph.nodes)
    }
  }

  duplicate(id: string): WorkflowRecord | null {
    const current = this.readWithoutTouch(id)
    if (!current) return null
    const now = new Date().toISOString()
    const copy: WorkflowRecord = {
      ...current,
      id: generateId(),
      name: `${current.name} (copy)`.slice(0, 120),
      createdAt: now,
      updatedAt: now,
      lastOpenedAt: now,
      graph: structuredClone(current.graph)
    }
    this.persistRecord(copy)
    this.upsertIndex(copy)
    return copy
  }

  delete(id: string): boolean {
    try {
      fs.rmSync(this.filePathFor(id))
      this.index.update((prev) => {
        prev.workflows = prev.workflows.filter((wf) => wf.id !== id)
        return prev
      })
      return true
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'ENOENT') {
        this.logger.error(`Failed to delete workflow '${id}'.`, error)
      }
      return false
    }
  }

  /* helpers --------------------------------------------------------- */

  private readWithoutTouch(id: string): WorkflowRecord | null {
    try {
      const raw = fs.readFileSync(this.filePathFor(id), 'utf8')
      const record = JSON.parse(raw) as WorkflowRecord
      return isRecordShape(record) ? record : null
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'ENOENT') {
        this.logger.error(`Failed to read workflow '${id}'.`, error)
      }
      return null
    }
  }

  private persistRecord(record: WorkflowRecord): void {
    fs.mkdirSync(this.dataDir, { recursive: true })
    const tmp = path.join(this.dataDir, `${record.id}.tmp`)
    fs.writeFileSync(tmp, JSON.stringify(record, null, 2), 'utf8')
    fs.renameSync(tmp, this.filePathFor(record.id))
  }

  private upsertIndex(record: WorkflowRecord): void {
    const summary: WorkflowSummary = {
      id: record.id,
      name: record.name,
      description: record.description,
      createdAt: record.createdAt,
      updatedAt: record.updatedAt,
      lastOpenedAt: record.lastOpenedAt
    }
    this.index.update((prev) => {
      const rest = prev.workflows.filter((wf) => wf.id !== record.id)
      prev.workflows = [summary, ...rest]
      return prev
    })
  }
}

/* ------------------------------------------------------------------ */

interface IndexedWorkflow extends WorkflowSummary {
  lastOpenedAt: string | null
}

interface WorkflowIndex {
  version: 1
  workflows: IndexedWorkflow[]
}

function defaultIndex(): WorkflowIndex {
  return { version: 1, workflows: [] }
}

function isRecordShape(value: unknown): value is WorkflowRecord {
  if (typeof value !== 'object' || value === null) return false
  const record = value as WorkflowRecord
  const graph = record.graph as WorkflowGraph | undefined
  return (
    typeof record.id === 'string' &&
    typeof record.name === 'string' &&
    typeof record.createdAt === 'string' &&
    typeof record.updatedAt === 'string' &&
    typeof graph === 'object' &&
    graph !== null &&
    typeof (graph as WorkflowGraph).schemaVersion === 'number' &&
    Array.isArray((graph as WorkflowGraph).nodes) &&
    Array.isArray((graph as WorkflowGraph).edges)
  )
}

/** A saved view is stored only when it is a sane finite number triple. */
export function sanitizeView(raw: unknown): { zoom: number; x: number; y: number } | null {
  if (typeof raw !== 'object' || raw === null) return null
  const view = raw as { zoom?: unknown; x?: unknown; y?: unknown }
  const zoom = Number(view.zoom)
  const x = Number(view.x)
  const y = Number(view.y)
  if (!Number.isFinite(zoom) || !Number.isFinite(x) || !Number.isFinite(y)) return null
  if (zoom <= 0) return null
  return { zoom, x, y }
}

/** Defensive pass-through keep only what the schema knows about. */
export function sanitizeGraph(graph: WorkflowGraph): WorkflowGraph {
  const nodes = (Array.isArray(graph?.nodes) ? graph.nodes : []).map((node) => ({
    id: String(node?.id ?? ''),
    type: node?.type,
    position: {
      x: Number((node as WorkflowNode | undefined)?.position?.x ?? 0),
      y: Number((node as WorkflowNode | undefined)?.position?.y ?? 0)
    },
    config: ((node as WorkflowNode | undefined)?.config ?? {}) as Record<string, unknown>
  })) as WorkflowNode[]
  const edges = (Array.isArray(graph?.edges) ? graph.edges : []).map((edge) => {
    const asEdge = edge as Partial<WorkflowEdge>
    return {
      id: String(asEdge?.id ?? ''),
      source: String(asEdge?.source ?? ''),
      target: String(asEdge?.target ?? ''),
      ...(typeof asEdge?.sourceHandle === 'string' ? { sourceHandle: asEdge.sourceHandle } : {})
    } satisfies WorkflowEdge
  })
  return { schemaVersion: Number(graph?.schemaVersion ?? WORKFLOW_SCHEMA_VERSION), nodes, edges }
}

/**
 * "Saved, but not runnable yet" messages: one concise note per node with
 * missing required configuration, taken from the shared validator so
 * both renderer and persistence agree on what is missing.
 */
function incompleteNodeMessages(nodes: WorkflowNode[]): Array<{ nodeId: string; message: string }> {
  const fullResult = validateWorkflowGraph({
    schemaVersion: WORKFLOW_SCHEMA_VERSION,
    nodes,
    edges: []
  })
  const byNode = new Map<string, string>()
  for (const issue of fullResult.configIssues as GraphValidationIssue[]) {
    if (!issue.nodeId || byNode.has(issue.nodeId)) continue
    byNode.set(issue.nodeId, issue.message)
  }
  return [...byNode.entries()].map(([nodeId, message]) => ({ nodeId, message }))
}

function generateId(): string {
  return `wf_${Date.now().toString(36)}${Math.random().toString(36).slice(2, 10)}`
}
